// Per venue rules: formula on its own line; number (if the formula is referenced
// elsewhere by number) tab-stopped at 14 cm; trailing comma/period is plain text,
// never typed inside the equation editor itself.
function formulaPara(mathChildren, opts = {}) {
  const kids = [];
  if (opts.lead) kids.push(t(opts.lead));
  kids.push(new DocxMath({ children: mathChildren }));
  kids.push(t(opts.punct || "."));
  if (opts.num) kids.push(new TextRun({ text: `\t(${opts.num})`, font: FONT, size: SZ }));
  return new Paragraph({
    tabStops: opts.num ? [{ type: TabStopType.RIGHT, position: TAB_14CM }] : undefined,
    spacing: { before: 100, after: 100, line: 240 },
    alignment: AlignmentType.LEFT,
    children: kids,
  });
}

