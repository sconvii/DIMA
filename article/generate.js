// ---------- helpers ----------
function t(text, opts = {}) {
  return new TextRun({
    text,
    font: FONT,
    size: opts.size || SZ,
    italics: !!opts.i,
    bold: !!opts.b,
    subScript: !!opts.sub,
    superScript: !!opts.sup,
  });
}

function body(text, opts = {}) {
  return new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { line: 360, after: 160 },
    indent: opts.noIndent ? undefined : { firstLine: 500 },
    children: [t(text, { size: opts.size })],
  });
}

function multiRunPara(runs, opts = {}) {
  return new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { line: 360, after: 160 },
    indent: opts.noIndent ? undefined : { firstLine: 500 },
    children: runs,
  });
}

function formula(runs, num) {
  const children = [...runs];
  const para = new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 120 },
    tabStops: [{ type: "right", position: 9350 }],
    children: num ? [...children, new TextRun({ text: `\t(${num})`, font: FONT, size: SZ })] : children,
  });
  return para;
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 320, after: 160 },
    children: [new TextRun({ text, font: FONT, size: 28, bold: true })],
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 220, after: 120 },
    children: [new TextRun({ text, font: FONT, size: 24, bold: true, italics: true })],
  });
}

function labelPara(label, text, opts = {}) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: 360, after: 160 },
    children: [
      new TextRun({ text: label, font: FONT, size: SZ, bold: true }),
      new TextRun({ text, font: FONT, size: SZ }),
    ],
  });
}

function refItem(num, text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: 300, after: 100 },
    indent: { left: 500, hanging: 500 },
    children: [new TextRun({ text: `${num}. ${text}`, font: FONT, size: SZ_SMALL })],
  });
}

// ---------- table helpers ----------
function cell(text, opts = {}) {
  return new TableCell({
    width: { size: opts.width, type: WidthType.DXA },
    verticalAlign: VerticalAlign.CENTER,
    shading: opts.shade ? { type: ShadingType.CLEAR, fill: "D9D9D9" } : undefined,
    margins: { top: 80, bottom: 80, left: 100, right: 100 },
    children: [
      new Paragraph({
        alignment: opts.align || AlignmentType.CENTER,
        children: [
          new TextRun({
            text,
            font: FONT,
            size: SZ_SMALL,
            bold: !!opts.bold,
            italics: !!opts.italic,
          }),
        ],
      }),
    ],
  });
}

